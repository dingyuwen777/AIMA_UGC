def test_reset_recovers_missing_database_after_drop_failure(workspace, monkeypatch):
    """DROP后CREATE失败仍能通过正式reset恢复，未知重建库则不能删除。"""
    paths, target = workspace
    seed.initialize(paths, target=target)
    monkeypatch.setattr(seed, "local_target", lambda _: target)
    monkeypatch.setattr("builtins.input", lambda _: "RESET aima_ugc")
    original = seed.DatabaseTarget.psql
    failed = False

    def fail_create(self, sql, **kwargs):
        nonlocal failed
        if sql.startswith("CREATE DATABASE") and not failed:
            failed = True
            raise snapshot.SnapshotError("injected create failure")
        return original(self, sql, **kwargs)

    monkeypatch.setattr(seed.DatabaseTarget, "psql", fail_create)
    with pytest.raises(snapshot.SnapshotError, match="injected"):
        seed.reset(paths, execute=True)
    assert target.identity()["database_oid"] is None
    seed.reset(paths, execute=True)
    assert target.empty()
    assert seed.read_state(paths) is None
    assert (paths.data / "artifacts/raw/fixture.json").exists()


def test_reset_dry_run_wrong_confirmation_and_foreign_rebuild_are_safe(workspace, monkeypatch):
    """只读预览/错误确认不写；reset中断后陌生重建库不能被旧marker删除。"""
    paths, target = workspace
    seed.initialize(paths, target=target)
    monkeypatch.setattr(seed, "local_target", lambda _: target)
    before = target.read_shared_state()
    seed.reset(paths, execute=False)
    assert target.read_shared_state() == before
    monkeypatch.setattr("builtins.input", lambda _: "wrong")
    with pytest.raises(snapshot.SnapshotError, match="确认词"):
        seed.reset(paths, execute=True)
    assert target.read_shared_state() == before
    pending = {**before, "status": "resetting", "reset_phase": "drop_pending"}
    seed.persist_state(paths, target, pending)
    target.psql(f"DROP DATABASE {snapshot.quote(target.database)};", database="postgres")
    target.psql(f"CREATE DATABASE {snapshot.quote(target.database)};", database="postgres")
    target.psql("CREATE TABLE foreign_data(id int); INSERT INTO foreign_data VALUES (77);")
    monkeypatch.setattr("builtins.input", lambda _: "RESET aima_ugc")
    with pytest.raises(snapshot.SnapshotError, match="陌生"):
        seed.reset(paths, execute=True)
    assert target.psql("SELECT id FROM foreign_data;") == "77"


