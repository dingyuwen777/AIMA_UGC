def test_advisory_lock_and_live_connections_prevent_writes(workspace) -> None:
    """并发恢复/reset共用postgres库锁，API样连接存在时也拒绝恢复。"""
    import psycopg

    paths, target = workspace
    with target.lock():
        with pytest.raises(snapshot.SnapshotError, match="正在进行"):
            seed.initialize(paths, target=target)
    with psycopg.connect(
        host=target.host,
        port=target.port,
        user=target.user,
        password=target.password_file.read_text(),
        dbname=target.database,
    ):
        with pytest.raises(snapshot.SnapshotError, match="仍有连接"):
            seed.initialize(paths, target=target)
    assert target.empty()
    assert seed.read_state(paths) is None


def test_internal_autovacuum_does_not_block_but_client_connections_do(workspace) -> None:
    """真实后台维护不能冒充业务连接，仍拒绝另一个客户端连接。"""
    import psycopg

    _, target = workspace
    target.psql("ALTER SYSTEM SET autovacuum_naptime='1s';")
    target.psql("SELECT pg_reload_conf();")
    target.psql(
        "CREATE TABLE seed_autovacuum_probe(payload text) WITH "
        "(autovacuum_vacuum_insert_threshold=1,autovacuum_vacuum_insert_scale_factor=0,"
        "autovacuum_analyze_threshold=1,autovacuum_analyze_scale_factor=0,"
        "autovacuum_vacuum_cost_delay=20,autovacuum_vacuum_cost_limit=1); "
        "ALTER TABLE seed_autovacuum_probe ALTER COLUMN payload SET STORAGE PLAIN; "
        "INSERT INTO seed_autovacuum_probe SELECT repeat('a',2000) FROM generate_series(1,10000);"
    )
    worker = ""
    try:
        for _ in range(80):
            worker = target.psql(
                "SELECT pid FROM pg_stat_activity WHERE datname=current_database() "
                "AND backend_type='autovacuum worker' "
                "AND query LIKE '%seed_autovacuum_probe%' LIMIT 1;"
            )
            if worker:
                break
            time.sleep(0.25)
        assert worker, "隔离测试必须实际观察到 autovacuum worker"
        with target.lock() as connection:
            target.assert_idle(connection)
            with psycopg.connect(
                host=target.host,
                port=target.port,
                user=target.user,
                password=target.password_file.read_text(),
                dbname=target.database,
            ):
                with pytest.raises(snapshot.SnapshotError, match="仍有连接"):
                    target.assert_idle(connection)
    finally:
        if worker:
            target.psql(f"SELECT pg_cancel_backend({int(worker)});")
        target.psql("DROP TABLE IF EXISTS seed_autovacuum_probe;")
        target.psql("ALTER SYSTEM RESET autovacuum_naptime;")
        target.psql("SELECT pg_reload_conf();")


