def test_reset_does_not_adopt_database_created_immediately_after_drop(workspace, monkeypatch):
    """DROP返回前注入陌生重建，采样不得把陌生OID认领成absent的归属。"""
    paths, target = workspace
    seed.initialize(paths, target=target)
    previous = target.identity()
    monkeypatch.setattr(seed, "local_target", lambda _: target)
    monkeypatch.setattr("builtins.input", lambda _: "RESET aima_ugc")
    original = seed.DatabaseTarget.psql
    injected = False

    def rebuild_after_drop(self, sql, **kwargs):
        nonlocal injected
        result = original(self, sql, **kwargs)
        if sql.startswith("DROP DATABASE") and not injected:
            injected = True
            original(self, f"CREATE DATABASE {snapshot.quote(self.database)};", database="postgres")
            original(
                self, "CREATE TABLE foreign_data(id int); INSERT INTO foreign_data VALUES(77);"
            )
        return result

    monkeypatch.setattr(seed.DatabaseTarget, "psql", rebuild_after_drop)
    with pytest.raises(snapshot.SnapshotError, match="陌生"):
        seed.reset(paths, execute=True)
    assert target.read_shared_state()["identity"] == previous
    with pytest.raises(snapshot.SnapshotError, match="陌生"):
        seed.reset(paths, execute=True)
    assert target.psql("SELECT id FROM foreign_data;") == "77"
